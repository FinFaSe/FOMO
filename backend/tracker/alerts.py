"""Watchlist alerts (buy, sell, convergence) and their delivery.

Alerts come from trades, whichever path stored them (watcher, webhook, sync job), so they are generated by
scanning trades newer than a cursor. Only recent trades alert: syncing a wallet's history must not replay months
of buys. Convergence = at least N distinct entities on the watchlist buying the same mint within a window; linked
wallets (same funder, co-buys) count once, so one actor with five wallets is not five confirmations.

Each alert keeps the trade's block time, when the transaction was downloaded and when the alert was created, so
detection and alert latency can be measured (and later used to backtest copying with a realistic delay).
"""

import os
import time
from datetime import datetime, timezone
from decimal import Decimal

import httpx
from sqlalchemy import func, select

from .adapters.solana import ProviderError
from .backtest import schedule_alert_quotes
from .db import Alert, AlertState, RawTransaction, TokenQuote, Trade, Wallet, now_iso
from .entities import entity_index

KINDS = ("buy", "sell", "convergence")
MAX_DELIVERY_ATTEMPTS = 3


def settings() -> dict:
    return {"max_age_minutes": float(os.getenv("TRACKER_ALERT_MAX_AGE_MINUTES", "10")),
            "convergence_min": int(os.getenv("TRACKER_CONVERGENCE_MIN", "3")),
            "convergence_minutes": float(os.getenv("TRACKER_CONVERGENCE_MINUTES", "60"))}


def _iso(ts: int | None) -> str | None:
    return datetime.fromtimestamp(ts, timezone.utc).isoformat() if ts is not None else None


def _seconds_since(ts: int | None, iso: str | None) -> float | None:
    if ts is None or iso is None:
        return None
    return round(datetime.fromisoformat(iso).timestamp() - ts, 1)


def alert_json(a: Alert) -> dict:
    return {"id": a.id, "kind": a.kind, "wallet": a.wallet, "mint": a.mint, "signature": a.signature,
            "event_time": _iso(a.event_time), "detected_at": a.detected_at, "created_at": a.created_at,
            "detection_seconds": _seconds_since(a.event_time, a.detected_at),
            "alert_seconds": _seconds_since(a.event_time, a.created_at),
            "transaction_url": f"https://solscan.io/tx/{a.signature}" if a.signature else None,
            "details": a.details, "read": a.read, "delivery": {"state": a.delivery_state,
                                                               "attempts": a.delivery_attempts,
                                                               "error": a.delivery_error,
                                                               "delivered_at": a.delivered_at}}


def _trade_details(t: Trade, wallet: Wallet, groups: dict, symbol: str | None) -> dict:
    d = t.details
    usd = d.get("usd") or {}
    entity = groups.get(t.wallet)
    return {"label": wallet.label, "symbol": symbol, "token_amount": d["token_amount"],
            "quote_asset": d.get("quote_asset"), "quote_amount": d.get("quote_amount"),
            "usd": usd.get("gross_usd"), "price_usd": usd.get("price_usd"),
            "market_cap_usd": usd.get("market_cap_usd"),
            "market_cap_status": d["evidence"].get("market_cap", "unknown"), "venues": d.get("venues", []),
            "trade": d["evidence"].get("trade"), "entity": {"id": entity["id"], "size": entity["size"]}
            if entity else None}


def generate_alerts(session) -> dict:
    """Create alerts for favorite wallets' recent trades stored since the last scan. Idempotent."""
    cfg = settings()
    state = session.get(AlertState, 1)
    if state is None:
        state = AlertState(id=1, last_trade_id=0)
        session.add(state)
    rows = list(session.scalars(select(Trade).where(Trade.id > state.last_trade_id).order_by(Trade.id)))
    report = {"scanned": len(rows), "created": 0}
    if not rows:
        session.commit()
        return report
    state.last_trade_id = rows[-1].id
    favorites = {w.address: w for w in session.scalars(select(Wallet).where(Wallet.favorite.is_(True)))}
    now = time.time()
    fresh = [t for t in rows if t.wallet in favorites and t.kind in ("buy", "sell") and t.block_time is not None
             and now - t.block_time <= cfg["max_age_minutes"] * 60]
    if not fresh:
        session.commit()
        return report
    groups = entity_index(session)
    symbols = {q.mint: q.symbol for q in session.scalars(select(TokenQuote).where(
        TokenQuote.mint.in_(sorted({t.mint for t in fresh}))))}
    webhook = "pending" if Notifier().configured else "off"
    existing = set(session.scalars(select(Alert.key).where(Alert.key.in_(
        [f"{t.kind}:{t.wallet}:{t.signature}:{t.event_index}" for t in fresh]))))

    created: list[Alert] = []

    def add(alert: Alert):
        if alert.key in existing:
            return
        existing.add(alert.key)
        alert.delivery_state = webhook
        alert.created_at = now_iso()
        session.add(alert)
        created.append(alert)
        report["created"] += 1

    for t in fresh:
        raw = session.get(RawTransaction, t.signature)
        add(Alert(key=f"{t.kind}:{t.wallet}:{t.signature}:{t.event_index}", kind=t.kind, wallet=t.wallet,
                  mint=t.mint, signature=t.signature, event_time=t.block_time,
                  detected_at=raw.fetched_at if raw else None,
                  details=_trade_details(t, favorites[t.wallet], groups, symbols.get(t.mint))))
        if t.kind == "buy":
            convergence = _convergence(session, t, favorites, groups, cfg, symbols.get(t.mint))
            if convergence is not None:
                existing |= set(session.scalars(select(Alert.key).where(Alert.key == convergence.key)))
                add(convergence)
    session.flush()  # alert ids for the prospective quote schedule
    schedule_alert_quotes(session, created)
    session.commit()
    return report


def _convergence(session, trigger: Trade, favorites: dict, groups: dict, cfg: dict, symbol) -> Alert | None:
    start = trigger.block_time - int(cfg["convergence_minutes"] * 60)
    buys = session.scalars(select(Trade).where(Trade.mint == trigger.mint, Trade.kind == "buy",
                                               Trade.wallet.in_(list(favorites)),
                                               Trade.block_time.between(start, trigger.block_time))
                           .order_by(Trade.block_time, Trade.id))
    by_entity: dict[str, Trade] = {}
    for b in buys:
        entity = groups.get(b.wallet)
        by_entity.setdefault(entity["id"] if entity else b.wallet, b)
    if len(by_entity) < cfg["convergence_min"]:
        return None
    first = min(b.block_time for b in by_entity.values())
    participants = [{"wallet": b.wallet, "label": favorites[b.wallet].label, "entity": entity_id,
                     "block_time": _iso(b.block_time), "usd": (b.details.get("usd") or {}).get("gross_usd"),
                     "market_cap_usd": (b.details.get("usd") or {}).get("market_cap_usd")}
                    for entity_id, b in sorted(by_entity.items(), key=lambda kv: kv[1].block_time)]
    raw = session.get(RawTransaction, trigger.signature)
    # One alert per new level: reaching 3 entities alerts once; a 4th entity alerts again.
    return Alert(key=f"convergence:{trigger.mint}:{first}:{len(by_entity)}", kind="convergence", wallet=None,
                 mint=trigger.mint, signature=trigger.signature, event_time=trigger.block_time,
                 detected_at=raw.fetched_at if raw else None,
                 details={"symbol": symbol, "entities": len(by_entity), "window_minutes": cfg["convergence_minutes"],
                          "first_buy": _iso(first), "participants": participants})


def alert_text(a: Alert) -> str:
    d = a.details
    token = d.get("symbol") or f"{a.mint[:5]}…{a.mint[-5:]}"
    if a.kind == "convergence":
        names = ", ".join(p["label"] or f"{p['wallet'][:5]}…" for p in d["participants"])
        return (f"[CONVERGENCIA] {d['entities']} grupos de tu watchlist compraron {token} en "
                f"{int(d['window_minutes'])} min: {names}. https://solscan.io/token/{a.mint}")
    verb = "compró" if a.kind == "buy" else "vendió"
    who = d.get("label") or f"{a.wallet[:5]}…{a.wallet[-5:]}"
    amount = f"USD {Decimal(d['usd']):,.2f}" if d.get("usd") else (
        f"{d['quote_amount']} {d['quote_asset']}" if d.get("quote_amount") else "importe desconocido")
    cap = f" · MC {'≈' if d.get('market_cap_status') == 'estimated' else ''}USD {Decimal(d['market_cap_usd']):,.0f}" \
        if d.get("market_cap_usd") else ""
    return f"[{'COMPRA' if a.kind == 'buy' else 'VENTA'}] {who} {verb} {token} por {amount}{cap}. {a.signature and 'https://solscan.io/tx/' + a.signature}"


class Notifier:
    """Outbound webhook (Slack, Discord, Telegram or generic JSON). The URL is a secret: never logged or shown."""

    def __init__(self, url: str | None = None, fmt: str | None = None, chat_id: str | None = None,
                 client: httpx.Client | None = None):
        self.url = url if url is not None else os.getenv("TRACKER_ALERT_WEBHOOK_URL")
        self.fmt = (fmt or os.getenv("TRACKER_ALERT_WEBHOOK_FORMAT", "json")).lower()
        self.chat_id = chat_id if chat_id is not None else os.getenv("TRACKER_ALERT_TELEGRAM_CHAT_ID")
        self.client = client

    @property
    def configured(self) -> bool:
        return bool(self.url) and self.url.startswith("https://") and (self.fmt != "telegram" or bool(self.chat_id))

    def body(self, a: Alert) -> dict:
        text = alert_text(a)
        if self.fmt == "slack":
            return {"text": text}
        if self.fmt == "discord":
            return {"content": text[:2000]}
        if self.fmt == "telegram":
            return {"chat_id": self.chat_id, "text": text, "disable_web_page_preview": True}
        return {"text": text, "alert": alert_json(a)}

    def send(self, a: Alert):
        client = self.client or httpx.Client(timeout=10, follow_redirects=False, trust_env=True)
        try:
            r = client.post(self.url, json=self.body(a))
        except httpx.HTTPError:
            raise ProviderError("Webhook de alertas inaccesible") from None
        if r.status_code >= 300:
            raise ProviderError(f"Webhook de alertas HTTP {r.status_code}")


def deliver_pending(session, notifier: Notifier | None = None, *, limit: int = 20) -> dict:
    notifier = notifier or Notifier()
    report = {"sent": 0, "failed": 0}
    if not notifier.configured:
        return report
    for a in session.scalars(select(Alert).where(Alert.delivery_state == "pending").order_by(Alert.id).limit(limit)):
        try:
            notifier.send(a)
            a.delivery_state, a.delivered_at, a.delivery_error = "sent", now_iso(), None
            report["sent"] += 1
        except ProviderError as exc:
            a.delivery_attempts += 1
            a.delivery_error = exc.message[:300]
            if a.delivery_attempts >= MAX_DELIVERY_ATTEMPTS:
                a.delivery_state = "failed"
            report["failed"] += 1
        session.commit()
    return report


def unread_count(session) -> int:
    return session.scalar(select(func.count()).select_from(Alert).where(Alert.read.is_(False)))
